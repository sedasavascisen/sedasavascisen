"""
Wideband (OFDM) helpers for thesis_exp/genis_bant. Same construction as thesis_exp/p4/common.Aging (aging set,
4 users, 8 BS antennas, 32-element RIS, 20 scatterers, ZF, soft-min beta = 8), with subcarriers generated by
MobileMuMisoChannel.generate(freq_offsets_hz=...) (same draws; phase-only re-evaluation at fc + df).

Evaluation grid: K_EVAL = 64 equally spaced subcarriers over bandwidth B (bin centres). The wideband user rate
is the mean over subcarriers of log2(1 + SINR_f) with a ZF precoder per subcarrier (fresh, as in the paper);
the metric is the minimum user rate. Optimization subsets: K_opt = 1 uses the centre frequency fc (narrowband
F, G, h_d); K_opt in {4, 16, 64} uses every (64 / K_opt)-th subcarrier of the evaluation grid.
"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "p4"))
import numpy as np, torch
from common import commit, ROOT                     # noqa: F401  (re-exported)
from ris_mu.mumiso.channel import make_mumiso_scenario
from ris_mu.mumiso.mobile import MobileConfig, MobileMuMisoChannel
from ris_mu.mumiso import system as S, baselines as B

K_EVAL = 64
KOPTS = [1, 4, 16, 64]


def offsets(bw_hz):
    return ((np.arange(K_EVAL) + 0.5) / K_EVAL - 0.5) * bw_hz


def subset(k_opt):
    # centred: every step-th subcarrier starting at step // 2 (centroid within half a bin of the band centre;
    # the earlier start at 0 put it ~0.12 B below the centre; changed before any curve run, ON_KAYIT.md sonradan kayıtlı sapma 1)
    step = K_EVAL // k_opt
    return list(range(step // 2, K_EVAL, step)) if k_opt > 1 else None


class WB:
    """times must start with 0.0 (same scenarios for any grid, see common.py)."""

    def __init__(self, seed, times, bw_hz, v=1.5, n=400):
        assert times[0] == 0.0
        torch.manual_seed(0)
        panel, base = make_mumiso_scenario(n_users=4, n_bs_antennas=8, seed=seed)
        cfg = MobileConfig(**{**base.__dict__, "velocity": v, "times_ms": tuple(times), "n_clusters": 20})
        d = MobileMuMisoChannel(panel, cfg).generate(n, freq_offsets_hz=offsets(bw_hz))
        c64 = lambda x: torch.as_tensor(x, dtype=torch.complex64)
        self.times = list(times)
        self.F, self.G0, self.H0 = c64(d["F"]), c64(d["G_t"][:, 0]), c64(d["hd_t"][:, 0])      # narrowband, t = 0
        self.Ff = c64(d["F_f"])                      # [S, Kf, N, T]
        self.Gtf = c64(d["G_tf"])                    # [S, M, Kf, K, N]
        self.Htf = c64(d["hd_tf"])                   # [S, M, Kf, K, T]
        self.pt, self.nv, self.n = 1.0, 1.0 / cfg.snr_scale(), n

    def user_rates(self, th, m, fidx=None):
        """[S, K] mean over subcarriers fidx (default: all K_EVAL) of the per-subcarrier ZF rate at grid index m."""
        fidx = range(K_EVAL) if fidx is None else fidx
        c, s = torch.cos(th), torch.sin(th)
        r = [S.rates(self.Ff[:, f], self.Gtf[:, m, f], self.Htf[:, m, f], c, s, self.pt, self.nv, "zf") for f in fidx]
        return torch.stack(r, 0).mean(0)

    def minrate(self, th, m):
        return self.user_rates(th, m).min(-1).values

    def _obj_rates(self, th, k_opt):
        if k_opt == 1:
            return S.rates(self.F, self.G0, self.H0, torch.cos(th), torch.sin(th), self.pt, self.nv, "zf")
        return self.user_rates(th, 0, subset(k_opt))

    def adam(self, start, L, k_opt, lr=0.5):
        dl = torch.zeros_like(start, requires_grad=True); opt = torch.optim.Adam([dl], lr=lr)
        for _ in range(L):
            R = self._obj_rates(start + dl, k_opt)
            (-(-torch.logsumexp(-8.0 * R, -1) / 8.0).mean()).backward(); opt.step(); opt.zero_grad()
        return (start + dl).detach()

    def su_average(self):
        return B.su_average(self.F, self.G0, self.H0, self.pt, self.nv)[1]

    def su_best_of(self):
        return B.su_best_of(self.F, self.G0, self.H0, self.pt, self.nv)[1]

    def cd(self, sweeps):
        return B.coord_descent(self.F, self.G0, self.H0, self.pt, self.nv, iters=sweeps)[1]


def check_t0_matches_narrowband(seed=11):
    """Sanity: the t = 0 narrowband channel of WB equals common.Aging's (same scenarios)."""
    from common import Aging
    w = WB(seed, [0.0], 20e6, n=8)
    a = Aging(seed, [0.0], n=8)
    return float((w.G0 - a.G[0]).abs().max()), float((w.F - a.F).abs().max())
